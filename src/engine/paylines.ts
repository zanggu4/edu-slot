import type { Cell } from './types'

/**
 * 25개 페이라인. 각 항목은 릴0..4의 행 번호 (0=위, 1=가운데, 2=아래).
 * 실제 기계에서 흔한 패턴: 가로 3개, V/역V, 지그재그, 산/골 등.
 */
export const PAYLINES: readonly (readonly number[])[] = [
  [1, 1, 1, 1, 1], // 1 가운데 가로
  [0, 0, 0, 0, 0], // 2 위 가로
  [2, 2, 2, 2, 2], // 3 아래 가로
  [0, 1, 2, 1, 0], // 4 V자
  [2, 1, 0, 1, 2], // 5 역V자
  [0, 0, 1, 0, 0], // 6
  [2, 2, 1, 2, 2], // 7
  [1, 0, 0, 0, 1], // 8
  [1, 2, 2, 2, 1], // 9
  [1, 0, 1, 0, 1], // 10 지그재그(위)
  [1, 2, 1, 2, 1], // 11 지그재그(아래)
  [0, 1, 0, 1, 0], // 12
  [2, 1, 2, 1, 2], // 13
  [0, 1, 1, 1, 0], // 14
  [2, 1, 1, 1, 2], // 15
  [1, 1, 0, 1, 1], // 16
  [1, 1, 2, 1, 1], // 17
  [0, 0, 2, 0, 0], // 18
  [2, 2, 0, 2, 2], // 19
  [0, 2, 2, 2, 0], // 20
  [2, 0, 0, 0, 2], // 21
  [1, 0, 2, 0, 1], // 22
  [1, 2, 0, 2, 1], // 23
  [0, 2, 0, 2, 0], // 24
  [2, 0, 2, 0, 2], // 25
]

export function paylineCells(lineNo: number): Cell[] {
  const rows = PAYLINES[lineNo - 1]
  if (!rows) throw new Error(`invalid line ${lineNo}`)
  return rows.map((row, reel) => ({ reel, row }))
}
